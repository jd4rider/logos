// StudyPlanWeek is one week for PDF rendering.
type StudyPlanWeek struct {
	WeekNumber int
	Theme      string
	Reading    string
	Verses     []string
	Notes      string
}

// ExportStudyPlan writes a multi-week study plan to a PDF file at outPath.
func ExportStudyPlan(title, description string, weeks []StudyPlanWeek, outPath string) error {
	pdf := newPDF()
	addFooter(pdf)
	pdf.AddPage()
	pdf.SetFillColor(colorLightR, colorLightG, colorLightB)
	pdf.Rect(0, 0, 210, 297, "F")

	addHeader(pdf, title, description)

	pdf.SetDrawColor(colorGoldR, colorGoldG, colorGoldB)
	pdf.SetLineWidth(0.4)
	pdf.Line(20, pdf.GetY(), 190, pdf.GetY())
	pdf.Ln(6)

	for _, w := range weeks {
		// Week header box
		pdf.SetFillColor(colorNavyR, colorNavyG, colorNavyB)
		pdf.SetTextColor(colorGoldR, colorGoldG, colorGoldB)
		pdf.SetFont("Helvetica", "B", 12)
		pdf.CellFormat(170, 8,
			fmt.Sprintf("  Week %d — %s", w.WeekNumber, sanitize(w.Theme)),
			"", 1, "L", true, 0, "")
		pdf.Ln(2)

		pdf.SetTextColor(colorTextR, colorTextG, colorTextB)
		pdf.SetFont("Helvetica", "B", 10)
		pdf.Cell(30, 6, "Reading:")
		pdf.SetFont("Helvetica", "", 10)
		pdf.MultiCell(140, 6, sanitize(w.Reading), "", "L", false)

		if len(w.Verses) > 0 {
			pdf.SetFont("Helvetica", "B", 10)
			pdf.Cell(30, 6, "Key Verses:")
			pdf.SetFont("Helvetica", "", 10)
			pdf.MultiCell(140, 6, sanitize(strings.Join(w.Verses, " • ")), "", "L", false)
		}

		pdf.SetFont("Helvetica", "B", 10)
		pdf.Cell(0, 6, "Study Notes & Reflection:")
		pdf.Ln(6)
		pdf.SetFont("Helvetica", "", 10)
		pdf.MultiCell(170, 5.5, sanitize(w.Notes), "", "J", false)
		pdf.Ln(6)

		// Light divider
		pdf.SetDrawColor(200, 195, 220)
		pdf.SetLineWidth(0.2)
		pdf.Line(20, pdf.GetY(), 190, pdf.GetY())
		pdf.Ln(4)
	}

	return pdf.OutputFileAndClose(outPath)
}

// ExportNote writes an AI verse note to PDF.
func ExportNote(verseRef, content, outPath string) error {
	pdf := newPDF()
	addFooter(pdf)
	pdf.AddPage()
	pdf.SetFillColor(colorLightR, colorLightG, colorLightB)
	pdf.Rect(0, 0, 210, 297, "F")

	addHeader(pdf, "Study Note", verseRef)
	pdf.Ln(4)
	writeBody(pdf, content)
	return pdf.OutputFileAndClose(outPath)
}
